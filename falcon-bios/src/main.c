/* The drive the BIOS booted from, and one other. Both are asked about,
 * because the rig's default image (make test-bios-img) boots a raw disk with
 * no partition table and puts the falcon partitions on the second one. On a
 * real machine the other drive is the internal disk, and nothing on it may
 * stand in for the stick's own p2 or p3; claim_roles is where that is
 * decided. */
#define DRIVE_FIRST  0x80u
#define DRIVE_SECOND 0x81u

/* Caller-allocated, as everywhere in falcon-core, and static rather than on
 * the stack because stage 3's stack is 64 KB (biosdefs.h, STAGE3_STACK).
 * One array per disk: g_p2_part and g_p3_part point into these for the life
 * of the loader, so a second parse into the same array would change which
 * partition they name. */
#define PARTS_MAX 16u
static gpt_part g_parts[PARTS_MAX];
static gpt_part g_parts_other[PARTS_MAX];

/* The ISO partition, once found, and the offset shim that turns a
 * disk-relative callback into a partition-relative one. Same shape as
 * medium.c's, and for the same reason: everything above wants to think it is
 * reading a volume from zero. */
typedef struct {
    bios_disk *disk;
    uint64_t   base;
} part_src;

static part_src g_p2_src;
static fs_vol   g_p2;
static int      g_p2_mounted;

/* p2's own GPT entry and the block size it was read with: between them they
 * are what names the partition to falcon-hook, which has to find the same
 * one from Linux (DESIGN Section 6.4). */
static const gpt_part *g_p2_part;
static uint32_t        g_p2_block;

/* p3 and the disk it is on, for the personal-OS row (DESIGN Section 5). */
static const gpt_part *g_p3_part;
static bios_disk      *g_p3_disk;

/* What the menu draws, from falcon-core's survey (media/survey.c): the same
 * walk, extension rule, sort and folder view the UEFI loader uses. The
 * results are kept rather than re-read, because re-walking to redraw a row
 * would mean a thunk call per sector per keystroke.
 *
 * ISO and IMG only: nothing on a BIOS machine runs a PE, so the .efi rows
 * the UEFI menu offers would be rows that cannot boot. */
#define MENU_MAX 64u
/* The core rows, plus "..", plus the personal-OS row. */
#define VIEW_MAX (MENU_MAX + 2u)

static survey_entry g_entries[MENU_MAX];
static survey_list  g_survey;
static survey_row   g_view[VIEW_MAX];

/* Where the menu is. Empty at p2's root. */
static uint16_t g_cur[SURVEY_PATH_MAX];
static size_t   g_cur_len;

/* Whether the menu has a personal-OS row, which it does when p3 opened as a
 * LUKS2 volume. One row, first on the root screen, as under UEFI. */
static int g_pos_row;

static int part_read(void *ctx, uint64_t off, uint64_t len, void *buf)
{
    const part_src *p = ctx;

    if (off > ~(uint64_t)0 - p->base)
        return -1;
    return bios_disk_read(p->disk, p->base + off, len, buf);
}

static void put_name(const uint16_t *name)
{
    size_t i;

    for (i = 0; name[i] != 0; i++)
        bios_putc(bios_ascii(name[i], '?'));
}

/* ---- the menu (DESIGN Section 6 stage 1) ----
 *
 * The rows are the UEFI loader's view_build, in its order: the personal-OS
 * row first on the root screen, ".." first in a folder, then the folders and
 * files the survey found. What a folder holds comes from falcon-core
 * (media/survey.c), so the two platforms cannot disagree about what is on a
 * stick; how the menu is drawn comes from falcon-core too (tui/tui.c), so
 * they cannot disagree about how it looks. The UEFI menu's firmware-setup
 * row has no counterpart: nothing asks a BIOS to open its setup screen. */

typedef enum {
    ROW_PERSONAL,   /* the personal-OS row; root screen only */
    ROW_UP,         /* leave the current folder */
    ROW_DIR,        /* descend into the folder this row names */
    ROW_IMAGE       /* boot survey entry g_row_index */
} row_kind;

static const uint16_t *g_labels[VIEW_MAX];
static row_kind        g_kind[VIEW_MAX];
static size_t          g_row_index[VIEW_MAX];

/* The ".." row doubles as the only place the current folder is named, as
 * on the UEFI menu. */
static uint16_t g_up_label[SURVEY_PATH_MAX + 16u];

static void up_label(void)
{
    static const uint16_t head[] = u"..  (now in /";
    size_t n = 0;
    size_t i;

    for (i = 0; head[i] != 0 && n + 2u < sizeof g_up_label / 2u; i++)
        g_up_label[n++] = head[i];
    for (i = 0; i < g_cur_len && n + 2u < sizeof g_up_label / 2u; i++)
        g_up_label[n++] = g_cur[i];
    g_up_label[n++] = u')';
    g_up_label[n] = 0;
}

static size_t view_build(void)
{
    size_t n = 0;
    size_t j;
    size_t i;

    if (g_cur_len == 0u) {
        if (g_pos_row) {
            g_labels[n] = pos_entry_label();
            g_kind[n] = ROW_PERSONAL;
            n++;
        }
    } else {
        up_label();
        g_labels[n] = g_up_label;
        g_kind[n] = ROW_UP;
        n++;
    }
    j = survey_view(&g_survey, g_cur, g_cur_len, g_view, VIEW_MAX - n);
    for (i = 0; i < j && n < VIEW_MAX; i++) {
        g_labels[n] = g_view[i].label;
        g_kind[n] = (g_view[i].kind == SURVEY_ROW_DIR) ? ROW_DIR : ROW_IMAGE;
        g_row_index[n] = (size_t)g_view[i].index;
        n++;
    }
    return n;
}

/* ---- boot routes, reported the way the UEFI loader reports them ---- */

static const char k_press_any[] = "\npress any key to return to the menu.\n";

/* A route's first screen: its code, then what is being booted. */
static void booting(const char *code, const uint16_t *label)
{
    screen_mode(code);
    screen_page();
    screen_out("booting: ");
    screen_out16(label);
    screen_out("\n\n");
}

/* A route that came back: "<what> failed while <stage>", then the advice. */
static void failed(const char *what, const boot_result *r)
{
    screen_out("\n");
    screen_out(what);
    screen_out(" failed while ");
    screen_out(r->stage);
    screen_out("\n");
    if (r->advice != (const char *)0) {
        screen_out("\n");
        screen_out(r->advice);
        screen_out("\n");
    }
}

/* Windows install media with boot.wim patched in memory (DESIGN Section
 * 6.4). 0 when the medium is not one the patch applies to, with the caller
 * left to boot it as it is. */
static int boot_windows(const survey_entry *e)
{
    char rel[MANIFEST_PATH_MAX];
    boot_result r;
    int unpatchable = 1;

    /* The whole path from p2's root, not the file's name: winjump looks for
     * exactly this under every drive letter, and an ISO in a folder is not
     * at the root of any of them. Converted by the rule the UEFI loader and
     * the manifest use, so a path it cannot carry is booted unpatched
     * rather than turned into one winjump will never find. */
    if (manifest_path_from_ucs2(e->label, rel, sizeof rel) != MANIFEST_OK)
        return 0;
    boot_result_init(&r);
    booting("WIN", e->label);
    (void)win_boot(g_p2_src.disk, &g_p2, g_p2_part, &e->ent, rel, &r,
                   &unpatchable);
    if (unpatchable)
        return 0;

    screen_page();
    screen_out16(e->label);
    failed("boot", &r);
    screen_out(k_press_any);
    return 1;
}

/* A BSD medium served as its own memory disk (docs/notes/bsd-route.md). 0
 * when the medium is not one this route applies to. */
static int boot_bsd(const survey_entry *e)
{
    boot_result r;
    int not_bsd = 1;

    boot_result_init(&r);
    booting("BSD", e->label);
    (void)bsd_boot(g_p2_src.disk, &g_p2, g_p2_part, &e->ent, &r, &not_bsd);
    if (not_bsd)
        return 0;

    screen_page();
    screen_out16(e->label);
    failed("the memory-disk boot", &r);
    screen_out(k_press_any);
    return 1;
}

/* The ISO's kernel, directly, with falcon-hook (DESIGN Section 6.4). An ISO
 * with no boot entry this loader can take stops here with the key that
 * boots its own loader, rather than falling through to it: on this
 * platform that is a separate choice (docs/Manual.md, Section 1.3). */
static void boot_direct(const survey_entry *e)
{
    boot_result r;

    boot_result_init(&r);
    booting("DIR", e->label);
    (void)scan_direct(&g_p2, g_p2_part, &e->ent, g_p2_block, &r);

    screen_page();
    screen_out16(e->label);
    if (r.title[0] != '\0') {
        screen_out("\nentry: ");
        screen_out(r.title);
    }
    failed("direct boot", &r);
    screen_out("\npress c on the entry to boot the ISO's own loader "
               "instead.\n");
    screen_out(k_press_any);
}

/* The medium's own bootloader, off the resident virtual CD. */
static void boot_target(const survey_entry *e, const family_desc *fam)
{
    boot_result r;

    boot_result_init(&r);
    booting("CHN", e->label);
    (void)scan_chain(g_p2_src.disk, &g_p2, g_p2_part, &e->ent, &r);

    screen_page();
    screen_out16(e->label);
    if (fam != (const family_desc *)0) {
        screen_out("\nfamily: ");
        screen_out(fam->name);
    }
    failed("boot", &r);
    screen_out(k_press_any);
}

/* What the UEFI loader's boot_plain decides, in its order: Windows media is
 * patched, BSD media is served as a memory disk, anything else boots its
 * kernel directly, and c boots the medium's own loader. The one difference
 * is BSD media this route does not apply to, which goes on to the direct
 * boot here rather than to the chainload (docs/Manual.md, Section 1.3). */
static void boot_plain(size_t idx, int which)
{
    const survey_entry *e = &g_survey.entries[idx];
    const family_desc *fam = scan_family(&g_p2, &e->ent);
    int chain = (which == 'c');
    int id = (fam != (const family_desc *)0) ? (int)fam->id : -1;

    if (!chain && id == (int)FAMILY_WINDOWS) {
        if (!boot_windows(e))
            boot_target(e, fam);
        return;
    }
    if (!chain && id == (int)FAMILY_BSD && boot_bsd(e))
        return;
    if (!chain) {
        boot_direct(e);
        return;
    }
    boot_target(e, fam);
}

/* The personal-OS row (DESIGN Section 5). 0 when the user backed out, which
 * leaves nothing on screen worth a keypress. */
static int boot_personal(void)
{
    boot_result r;

    screen_mode("POS");
    screen_page();
    screen_out16(pos_entry_label());
    screen_out("\n\n");
    if (pos_run(g_p3_disk, g_p3_part, &r) == POS_ABORTED)
        return 0;
    failed("personal OS boot", &r);
    screen_out(k_press_any);
    return 1;
}

/* Escape at the root, as on the UEFI menu: say so, and give the machine back
 * to its firmware, which on a BIOS is INT 18h, the call a boot sector makes
 * when it has nothing to boot. A BIOS that answers it by returning gets a
 * reset instead. */
static void return_to_firmware(void)
{
    screen_mode((const char *)0);
    screen_page();
    screen_out("falcon-boot: returning to firmware.\n");
    if (!g_p2_mounted)
        screen_out("note: no readable ISO volume was found.\n");
    if (g_survey.skipped != 0) {
        screen_out("note: ");
        screen_out_dec(g_survey.skipped);
        screen_out(" image(s) not shown (list full or path too long)\n");
    }
    thunk_vector = 0x18;
    thunk_bios();
    bios_reboot();
}

static void menu_run(void)
{
    static const screen_banner banner = {
        u"falcon-boot " FALCON_VERSION, u"BIOS", TUI_ATTR_TEXT
    };
    /* c and d choose the route for an ISO row; on any other row they act
     * as enter. */
    static const uint16_t hint[] =
        u"enter boot | c chain | d direct | esc back";

    for (;;) {
        size_t n;
        int which = BIOS_KEY_ENTER;
        int pick;

        /* Whatever route the last boot took, it is over. */
        screen_mode((const char *)0);
        n = view_build();
        pick = screen_menu(&banner, g_labels, n, "cd", hint, &which);

        if (pick < 0) {
            /* Escape is "back": out of the folder while there is one to
             * leave, out of the loader at the root. */
            if (g_cur_len != 0u) {
                survey_up(g_cur, &g_cur_len);
                continue;
            }
            return_to_firmware();
        }

        switch (g_kind[pick]) {
        case ROW_UP:
            survey_up(g_cur, &g_cur_len);
            continue;
        case ROW_DIR:
            (void)survey_enter(g_cur, &g_cur_len, g_labels[pick]);
            continue;
        case ROW_PERSONAL:
            if (!boot_personal())
                continue;
            break;
        case ROW_IMAGE:
        default:
            boot_plain(g_row_index[pick], which);
            break;
        }
        (void)screen_key();
    }
}

static bios_disk g_boot;
static bios_disk g_other;
static uint8_t g_sector[512];

/* Defined below, beside the exFAT state it uses. */
static void scan_iso_partition(bios_disk *d, const gpt_part *p);

static void show_first_sector(bios_disk *d, const char *what)
{
    bios_puts("falcon-bios: ");
    bios_puts(what);
    bios_puts(" drive ");
    bios_put_hex64(d->drive);
    bios_puts(", sector size ");
    bios_put_dec(d->sector_size);
    bios_puts("\n");

    if (bios_disk_read(d, 0, d->sector_size < sizeof g_sector
                              ? d->sector_size : sizeof g_sector,
                       g_sector) != 0) {
        bios_puts("falcon-bios:   LBA 0 unreadable\n");
        return;
    }
    bios_puts("falcon-bios:   LBA 0 ends ");
    bios_put_hex64((uint64_t)g_sector[510] | ((uint64_t)g_sector[511] << 8));
    bios_puts("\n");
}

static const char *gpt_error(int rc)
{
    switch (rc) {
    case GPT_ERR_IO:          return "the read callback failed";
    case GPT_ERR_NOT_GPT:     return "no GPT signature at LBA 1";
    case GPT_ERR_CRC:         return "a CRC did not check out";
    case GPT_ERR_BAD_ARG:     return "bad argument";
    case GPT_ERR_UNSUPPORTED: return "geometry this parser declines";
    default:                  return "unknown";
    }
}

/* Parses and prints one disk's partitions into `parts`. The count, 0 when
 * there is no table. */
static uint32_t show_partitions(bios_disk *d, gpt_part *parts)
{
    gpt_table t;
    uint32_t i;
    int rc;

    t.parts = parts;
    t.cap = PARTS_MAX;
    t.count = 0;
    t.truncated = 0;

    rc = gpt_parse(&t, bios_disk_read, d, d->sector_size);
    if (rc != GPT_OK) {
        bios_puts("falcon-bios:   no partition table: ");
        bios_puts(gpt_error(rc));
        bios_puts("\n");
        return 0;
    }

    bios_puts("falcon-bios:   GPT with ");
    bios_put_dec(t.count);
    bios_puts(" partition(s)");
    if (t.truncated)
        bios_puts(" (more than fitted)");
    bios_puts("\n");

    for (i = 0; i < t.count; i++) {
        bios_puts("falcon-bios:     p");
        bios_put_dec(parts[i].number);
        bios_puts("  LBA ");
        bios_put_dec(parts[i].start_lba);
        bios_puts("..");
        bios_put_dec(parts[i].end_lba);
        /* The roles DESIGN Section 3 identifies, asked of falcon-core's own
         * matcher rather than of a GUID comparison written again here. */
        if (gpt_part_is_role(&parts[i], PART_ROLE_ISO))
            bios_puts("  [falcon p2]");
        else if (gpt_part_is_role(&parts[i], PART_ROLE_SHELF))
            bios_puts("  [falcon p3]");
        bios_puts("\n");
    }
    return t.count;
}

/* The one the menu is built from, and the one the personal-OS row needs,
 * each taken from the first disk that has it: the boot disk is asked first,
 * so a machine's internal disk fills a role only when the disk it booted
 * from does not. Both are identified by DESIGN Section 3's rules, asked of
 * falcon-core's own matcher. */
static void claim_roles(bios_disk *d, gpt_part *parts, uint32_t n)
{
    uint32_t i;

    if (g_p3_part == (const gpt_part *)0) {
        for (i = 0; i < n; i++) {
            if (gpt_part_is_role(&parts[i], PART_ROLE_SHELF)) {
                g_p3_part = &parts[i];
                g_p3_disk = d;
                break;
            }
        }
    }
    if (g_p2_part == (const gpt_part *)0) {
        for (i = 0; i < n; i++) {
            if (gpt_part_is_role(&parts[i], PART_ROLE_ISO)) {
                scan_iso_partition(d, &parts[i]);
                break;
            }
        }
    }
}

/* Mount the falcon ISO partition and list what the menu would show.
 *
 * Through the registry, which identifies the filesystem rather than being
 * told it: p2 is exFAT today by DESIGN Section 3, and nothing here says so.
 * That was not possible in stage 2, where linking fs.c meant linking every
 * driver it knows and there were 33 KB for all of it. */
static void scan_iso_partition(bios_disk *d, const gpt_part *p)
{
    const fs_ops *ops;
    size_t i;

    g_p2_src.disk = d;
    g_p2_src.base = p->start_lba * (uint64_t)d->sector_size;
    g_p2_part = p;
    g_p2_block = d->sector_size;

    ops = fs_identify(part_read, &g_p2_src, FS_HINT_NONE);
    if (ops == (const fs_ops *)0) {
        bios_puts("falcon-bios:   no driver claimed p2\n");
        return;
    }
    if (fs_mount(&g_p2, ops, part_read, &g_p2_src) != FS_OK) {
        bios_puts("falcon-bios:   p2 would not mount\n");
        return;
    }
    g_p2_mounted = 1;
    bios_puts("falcon-bios:   p2 mounted as ");
    bios_puts(fs_vol_name(&g_p2));
    bios_puts(", label ");
    bios_puts(fs_vol_label(&g_p2));
    bios_puts("\n");

    survey_init(&g_survey, g_entries, MENU_MAX,
                SURVEY_ACCEPT_ISO | SURVEY_ACCEPT_IMG);
    if (survey_volume(&g_survey, &g_p2, 0) != 0) {
        bios_puts("falcon-bios:   p2 root unreadable\n");
        return;
    }
    survey_sort(&g_survey);

    /* The whole path, not the name: a stick with its images in Linux/ and
     * Windows/ is the normal case, and a serial log that printed bare names
     * could not tell two fedora.iso apart. */
    for (i = 0; i < g_survey.count; i++) {
        bios_puts("falcon-bios:     ");
        put_name(g_survey.entries[i].label);
        bios_puts("  ");
        bios_put_dec(g_survey.entries[i].ent.size);
        bios_puts(" bytes\n");
    }
    bios_puts("falcon-bios:   ");
    bios_put_dec(g_survey.count);
    bios_puts(" bootable image(s) on p2");
    if (g_survey.skipped != 0u) {
        bios_puts(", ");
        bios_put_dec(g_survey.skipped);
        bios_puts(" past the cap");
    }
    bios_puts("\n");
}

/* The memory map, which the loader needs to place an initrd and the kernel
 * needs because by the time it runs the call that answers is gone. */
static void show_memory(void)
{
    unsigned n = e820_read();
    unsigned i;
    uint64_t usable = 0;

    if (n == 0) {
        bios_puts("falcon-bios: no E820 memory map\n");
        return;
    }
    for (i = 0; i < n; i++) {
        const e820_entry *e = e820_at(i);

        if (e != (const e820_entry *)0 && e->type == E820_USABLE)
            usable += e->len;
    }
    bios_puts("falcon-bios: ");
    bios_put_dec(n);
    bios_puts(" E820 entries, ");
    bios_put_dec(usable / 1048576u);
    bios_puts(" MiB usable\n");
}

void bios_main(uint8_t drive)
{
    bios_puts("falcon-bios: C is running in protected mode\n");
    show_memory();

    if (!bios_disk_probe(&g_boot, drive))
        bios_puts("falcon-bios: the boot drive did not answer AH=48h\n");
    show_first_sector(&g_boot, "boot");
    claim_roles(&g_boot, g_parts, show_partitions(&g_boot, g_parts));

    if (bios_disk_probe(&g_other,
                        drive == DRIVE_FIRST ? DRIVE_SECOND : DRIVE_FIRST)) {
        show_first_sector(&g_other, "other");
        claim_roles(&g_other, g_parts_other,
                    show_partitions(&g_other, g_parts_other));
    }

    /* The personal-OS row, if p3 is there and is LUKS2. Asked once, before
     * the menu draws, because the answer does not change. */
    if (g_p3_part != (const gpt_part *)0)
        g_pos_row = pos_probe(g_p3_disk, g_p3_part);

    bios_puts("falcon-bios: done\n");
    screen_init();
    menu_run();
    for (;;)
        __asm__ __volatile__("hlt");
}
