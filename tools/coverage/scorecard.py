#!/usr/bin/env python3
"""falcon-boot: render the coverage scorecard (docs/coverage.md).

Reads the corpus manifest (tools/coverage/corpus.tsv) and every case result
under build/coverage/runs/<id>/<state>-<route>/result, and prints the
scorecard to stdout. tools/coverage/run-corpus.sh redirects it into
docs/coverage.md; nothing else writes that file.

A cell is the case's verdict. Which verdicts count as a pass for a column is
decided here, because it is a statement about the product rather than about
one boot:

  PASS         the OS reached userland (tools/coverage/run-case.sh)
  REFUSED      the platform refused an image. Under Secure Boot that is the
               design working when the image is one nobody vouched for
               (DESIGN Section 7.2), and the tier targets below do not count
               it against us for the drag-and-drop route; for a blessed image
               it is a failure.
  FAIL         anything else that did not reach userland
  UNBLESSABLE  the sign tool refused the ISO, so there is no blessed case
  N/A          the route does not exist for this media (Windows has no bless)
  ERROR        the harness failed, not the loader; always worth a look

The summary measures the roadmap's targets (Section 2): for each tier, the
share of ISOs that boot with Secure Boot off by drag and drop, and the share
that boot with Secure Boot on by any route the product offers.
"""

import os
import sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..')
MANIFEST = os.path.join(ROOT, 'tools', 'coverage', 'corpus.tsv')
RUNS = os.path.join(ROOT, 'build', 'coverage', 'runs')

STATES = [('off', 'SB off'), ('ms', 'SB on, MS CA'), ('own', 'SB on, own keys'),
          # Not a Secure Boot state: a BIOS machine has no db and no shim
          # (docs/notes/bios-route.md Section 3), so it is reported beside
          # the three rather than among them, and its blessed cell is N/A.
          ('bios', 'BIOS')]
ROUTE_ORDER = ['dnd', 'chain', 'blessed']
ROUTE_NAMES = {'dnd': 'drop', 'chain': 'chain', 'blessed': 'bless'}
# Headline: Secure Boot off, and Secure Boot on where db trusts the Microsoft
# CA, which is the overwhelmingly common machine. Secure Boot on with only the
# user's own keys is reported beside them without a target: media whose only
# signature is Microsoft's cannot boot there at all (DESIGN 7.2), so holding
# one number to both machines would only ever measure that.
TARGETS = {'A': (100, 95), 'B': (90, None), 'C': (None, None)}


def manifest():
    rows = []
    with open(MANIFEST) as f:
        for line in f:
            line = line.rstrip('\n')
            if not line or line.startswith('#'):
                continue
            cols = line.split('\t')
            if len(cols) < 6:
                continue
            rows.append({'id': cols[0], 'tier': cols[1], 'family': cols[2]})
    return rows


def result(case_id, state, route):
    d = os.path.join(RUNS, case_id, '%s-%s' % (state, route))
    try:
        with open(os.path.join(d, 'result')) as f:
            parts = f.readline().rstrip('\n').split('\t')
    except OSError:
        return None
    r = {'verdict': parts[0], 'reason': parts[1] if len(parts) > 1 else '',
         'secs': parts[2] if len(parts) > 2 else '', 'loader': ''}
    try:
        with open(os.path.join(d, 'loader')) as f:
            r['loader'] = f.readline().strip()
    except OSError:
        pass
    return r


def main():
    rows = manifest()
    routes = [rt for rt in ROUTE_ORDER
              if any(result(r['id'], st, rt) for r in rows for st, _ in STATES)]
    if not routes:
        routes = ['dnd', 'blessed']

    loaders = set()
    fails = []
    out = []
    w = out.append

    w('# Coverage scorecard')
    w('')
    w('Generated by `tools/coverage/run-corpus.sh` from the corpus in')
    w('`tools/coverage/corpus.tsv`; do not edit by hand. What a cell means is in')
    w('`tools/coverage/scorecard.py`, how a case is judged in')
    w('`tools/coverage/run-case.sh`, and the targets in')
    w('`docs/notes/coverage-roadmap.md` Section 2.')
    w('')
    w('Routes: **drop** is Enter on an unblessed image (whatever the loader does')
    w('by default), **chain** boots the ISO\'s own EFI loader, **bless** is Enter')
    w('on an image blessed with the sign tool.')
    w('')
    w('BIOS is a fourth column and not a Secure Boot state: that machine has')
    w('no db and no shim, so it has no blessed cell and nothing to refuse.')
    w('')
    w('The headline columns are Secure Boot off and Secure Boot on where db')
    w('trusts the Microsoft CA. Secure Boot on with only the stick owner\'s')
    w('keys is reported beside them, without a target: media signed only by')
    w('Microsoft cannot boot on such a machine at all (DESIGN 7.2).')
    w('')
    w('A cell reading "no userland on serial ... after starting <entry>" is a')
    w('measurement limit and not necessarily a failure. This harness reads')
    w('the serial console and a DHCP capture. A blessed wrap carries')
    w('console=ttyS0 because mk-case-stick.sh puts it there, and falcon-bios')
    w('appends it to a direct boot itself; a direct or chained boot under')
    w('UEFI runs the ISO\'s own cmdline, and an entry that writes to the')
    w('screen alone leaves both signals empty. Clonezilla is the worked')
    w('example (2026-09-20): its default entry is "Clonezilla live (VGA')
    w('800x600)", the screenshot beside the FAIL shows ocs-scan-disk running')
    w('and listing the disk it found, and serial stayed empty for 300s. Read')
    w('the screenshot before believing one of these.')
    w('')

    head = ['ISO', 'tier', 'family']
    for st, name in STATES:
        for rt in routes:
            head.append('%s %s' % (name, ROUTE_NAMES[rt]))
    table = ['| ' + ' | '.join(head) + ' |',
             '|' + '|'.join(['---'] * len(head)) + '|']

    tally = {}
    for r in rows:
        cells = [r['id'], r['tier'], r['family']]
        any_result = False
        off_ok = False
        ms_ok = False
        own_ok = False
        bios_ok = False
        for st, _ in STATES:
            state_ok = False
            for rt in routes:
                res = result(r['id'], st, rt)
                if res is None:
                    cells.append('-')
                    continue
                any_result = True
                if res['loader']:
                    loaders.add(res['loader'])
                v = res['verdict']
                cells.append(v)
                if v == 'PASS':
                    state_ok = True
                if v in ('FAIL', 'ERROR') or (v == 'REFUSED' and rt == 'blessed'):
                    fails.append((r['id'], st, rt, v, res['reason']))
            if st == 'off':
                off_ok = any((result(r['id'], 'off', rt) or {}).get('verdict')
                             == 'PASS' for rt in ('dnd',))
            elif st == 'ms':
                ms_ok = state_ok
            elif st == 'own':
                own_ok = state_ok
            elif st == 'bios':
                # Same rule as SB off: the drop route is the product's
                # default, and the headline is what it does.
                bios_ok = (result(r['id'], 'bios', 'dnd') or {}).get(
                    'verdict') == 'PASS' 
        table.append('| ' + ' | '.join(cells) + ' |')
        if any_result:
            t = tally.setdefault(r['tier'], [0, 0, 0, 0, 0])
            t[0] += 1
            t[1] += 1 if off_ok else 0
            t[2] += 1 if ms_ok else 0
            t[3] += 1 if own_ok else 0
            t[4] += 1 if bios_ok else 0

    w('Loader: ' + (', '.join(sorted(loaders)) if loaders else 'none recorded'))
    w('')
    w('## Summary')
    w('')
    w('| tier | ISOs run | SB off, drop | target | SB on, MS CA | target | '
      'SB on, own keys | BIOS, drop |')
    w('|---|---|---|---|---|---|---|---|')
    for tier in sorted(tally):
        n, off, ms, own, bios = tally[tier]
        toff, tms = TARGETS.get(tier, (None, None))
        w('| %s | %d | %d/%d (%d%%) | %s | %d/%d (%d%%) | %s | %d/%d (%d%%) '
          '| %d/%d (%d%%) |'
          % (tier, n, off, n, 100 * off // n,
             '%d%%' % toff if toff else '-',
             ms, n, 100 * ms // n, '%d%%' % tms if tms else '-',
             own, n, 100 * own // n, bios, n, 100 * bios // n))
    w('')
    w('## Matrix')
    w('')
    out.extend(table)
    w('')
    if fails:
        w('## Failures')
        w('')
        w('| ISO | state | route | verdict | reason |')
        w('|---|---|---|---|---|')
        for f in fails:
            w('| %s | %s | %s | %s | %s |' % (f[0], f[1], ROUTE_NAMES[f[2]],
                                             f[3], f[4].replace('|', '/')))
        w('')
    sys.stdout.write('\n'.join(out) + '\n')


if __name__ == '__main__':
    main()
