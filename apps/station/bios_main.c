/* falcon-bios, the stationary build (docs/DESIGN.md Section 13): stage 3's
 * entry point in falcon-bios-station-stage3.bin.
 *
 * The BIOS half of a machine's own boot loader. It boots the personal OS off
 * the boot disk's shelf and hands the machine to another disk's own boot code
 * (route MBR), and links nothing else: no ISO scan, virtual CD, Windows
 * media or BSD code is in this stage 3, and nothing is ever left resident.
 * Stages 1 and 2 are the stick's, unchanged; only the image stage 2 reads
 * from LBA 98 differs.
 *
 * It opens at the passphrase prompt, and Escape there or a failed boot lands
 * on the list, as the UEFI build's efi_main.c does; the sentences written
 * here follow that file and main.c's, and a change to one is a change to the
 * others (CLAUDE.md, "One screen, two loaders").
 */

#include <start/bios.h>

#include <pos/pos.h>
#include <mbr/mbr.h>
#include <console/screen.h>
#include <mem/e820.h>

#include <part/part.h>
#include <tui/tui.h>
#include <lib/ucs2.h>

/* Generated by make into build/: this build's version, with the pos-
 * variant, so a photo of the screen says which loader it is. */
#include <version.h>

/* The BDA's count of fixed disks, which is how many drive numbers from 0x80
 * up the BIOS answers for. */
#define BDA_NDISKS 0x475u

/* Disks this build looks at. The BDA's count is a byte, but a machine with
 * more than this many BIOS disks is not one this screen is for. */
#define DISKS_MAX 8u

#define PARTS_MAX 16u

/* Personal OS, one row per other disk. */
#define LIST_MAX (1u + DISKS_MAX)

typedef struct {
    bios_disk disk;
    gpt_part  parts[PARTS_MAX];
    uint32_t  nparts;
    int       boots;          /* LBA 0 carries the boot signature */
    uint16_t  label[32];
} disk_row;

static disk_row g_disks[DISKS_MAX];
static unsigned g_ndisks;
static unsigned g_boot_idx;   /* the boot drive's slot, or DISKS_MAX */

/* The shelf the personal OS comes from, and its disk. */
static const gpt_part *g_shelf;
static bios_disk      *g_shelf_disk;
static int             g_pos_row;

static const char k_press_any[] = "\npress any key to return to the menu.\n";

static void failed(const char *what, const boot_result *r)
{
    screen_out("\n");
    screen_out(what);
    screen_out(" failed while ");
    screen_out(r->stage);
    screen_out("\n");
    if (r->advice != (const char *)0) {
        screen_out("\n");
        screen_out(r->advice);
        screen_out("\n");
    }
}

/* "Disk 0x81", in UCS-2 for the menu. */
static void disk_label(disk_row *row)
{
    static const uint16_t head[] = u"Disk 0x";
    static const char hex[] = "0123456789abcdef";
    size_t n = 0;
    size_t i;

    for (i = 0; head[i] != 0; i++)
        row->label[n++] = head[i];
    row->label[n++] = (uint16_t)hex[(row->disk.drive >> 4) & 0xFu];
    row->label[n++] = (uint16_t)hex[row->disk.drive & 0xFu];
    row->label[n] = 0;
}

static uint32_t parse_gpt(disk_row *row)
{
    gpt_table t;

    t.parts = row->parts;
    t.cap = PARTS_MAX;
    t.count = 0;
    t.truncated = 0;
    if (gpt_parse(&t, bios_disk_read, &row->disk,
                  row->disk.sector_size) != GPT_OK)
        return 0;
    return t.count;
}

/* The first shelf on this disk that pos_probe opens. */
static int claim_shelf(disk_row *row)
{
    uint32_t i;

    for (i = 0; i < row->nparts && i < PARTS_MAX; i++) {
        if (!gpt_part_is_role(&row->parts[i], PART_ROLE_SHELF))
            continue;
        if (pos_probe(&row->disk, &row->parts[i])) {
            g_shelf = &row->parts[i];
            g_shelf_disk = &row->disk;
            return 1;
        }
    }
    return 0;
}

/* Every disk the BDA counts: its table, its boot signature, its label. */
static void scan_disks(uint8_t boot_drive)
{
    unsigned count = peek8(BDA_NDISKS);
    unsigned i;

    g_boot_idx = DISKS_MAX;
    for (i = 0; i < count && g_ndisks < DISKS_MAX; i++) {
        disk_row *row = &g_disks[g_ndisks];

        if (!bios_disk_probe(&row->disk, (uint8_t)(0x80u + i)))
            continue;
        row->nparts = parse_gpt(row);
        row->boots = mbr_bootable(&row->disk);
        disk_label(row);
        if (row->disk.drive == boot_drive)
            g_boot_idx = g_ndisks;
        bios_puts("falcon-bios: drive ");
        bios_put_hex64(row->disk.drive);
        bios_puts(", ");
        bios_put_dec(row->nparts);
        bios_puts(" GPT partition(s)");
        if (row->boots)
            bios_puts(", boot code in LBA 0");
        bios_puts("\n");
        g_ndisks++;
    }
}

/* The boot disk's shelf wins, and exclusively (DESIGN Section 13.3); other
 * disks are asked only when it has none that opens. */
static void pick_shelf(void)
{
    unsigned i;

    if (g_boot_idx < g_ndisks && g_boot_idx < DISKS_MAX &&
        claim_shelf(&g_disks[g_boot_idx]))
        return;
    for (i = 0; i < g_ndisks; i++) {
        if (i != g_boot_idx && claim_shelf(&g_disks[i]))
            return;
    }
}

static int boot_personal(void)
{
    boot_result r;

    screen_mode("POS");
    screen_page();
    screen_out16(pos_entry_label());
    screen_out("\n\n");
    if (pos_run(g_shelf_disk, g_shelf, &r) == POS_ABORTED)
        return 0;
    failed("personal OS boot", &r);
    screen_out(k_press_any);
    return 1;
}

static void boot_disk(disk_row *row)
{
    boot_result r;

    boot_result_init(&r);
    screen_mode("MBR");
    screen_page();
    screen_out("booting: ");
    screen_out16(row->label);
    screen_out("\n\n");
    (void)mbr_boot(&row->disk, &r);

    screen_page();
    screen_out16(row->label);
    failed("boot", &r);
    screen_out(k_press_any);
}

/* Escape on the list: as main.c, INT 18h, and a reset if the BIOS returns. */
static void return_to_firmware(void)
{
    screen_mode((const char *)0);
    screen_page();
    screen_out("falcon-boot: returning to firmware.\n");
    thunk_vector = 0x18;
    thunk_bios();
    bios_reboot();
}

static void list_run(void)
{
    static const screen_banner banner = {
        u"falcon-boot " FALCON_VERSION_STATION, u"BIOS", TUI_ATTR_TEXT
    };
    static const uint16_t *labels[LIST_MAX];
    static int kind[LIST_MAX];      /* -1 personal OS, else a g_disks slot */

    for (;;) {
        size_t n = 0;
        unsigned i;
        int pick;

        screen_mode((const char *)0);
        if (g_pos_row) {
            labels[n] = pos_entry_label();
            kind[n] = -1;
            n++;
        }
        for (i = 0; i < g_ndisks; i++) {
            if (i == g_boot_idx || !g_disks[i].boots)
                continue;
            labels[n] = g_disks[i].label;
            kind[n] = (int)i;
            n++;
        }

        pick = screen_menu(&banner, labels, n, (const char *)0,
                           tui_hint_plain, (int *)0);
        if (pick < 0)
            return_to_firmware();

        if (kind[pick] < 0) {
            if (!boot_personal())
                continue;
        } else {
            boot_disk(&g_disks[kind[pick]]);
        }
        (void)screen_key();
    }
}

void bios_main(uint8_t drive)
{
    unsigned n;

    bios_puts("falcon-bios: stationary build, protected mode\n");
    /* The kernel is placed by the map, and by the time it runs the call
     * that answers is gone. */
    n = e820_read();
    bios_puts("falcon-bios: ");
    bios_put_dec(n);
    bios_puts(" E820 entries\n");

    scan_disks(drive);
    pick_shelf();
    g_pos_row = (g_shelf != (const gpt_part *)0);

    screen_init();
    if (g_pos_row && boot_personal())
        (void)screen_key();
    list_run();
    for (;;)
        __asm__ __volatile__("hlt");
}
