/* falcon-bios, the station (docs/DESIGN.md Section 13): stage 3's entry
 * point in falcon-bios-station-stage3.bin.
 *
 * The BIOS half of a machine's own boot loader. It lists what it finds
 * (Section 13.3): the UKIs on every shelf carrying its install ID, each
 * primary partition whose boot sector is a known loader and each other disk
 * whose MBR has boot code and an active entry, on every disk, and
 * memtest86+ when the station partition carries MEMTEST.BIN. STATION.INI,
 * in the station partition's root, relabels, hides, orders and adds to
 * them and sets a default and a countdown (13.7); a next-boot marker names
 * one entry to start without the menu (13.8).
 *
 * Routes: POS (a UKI off a shelf, pos.c), VBR (a partition's boot sector)
 * and MBR (another disk's own boot code), both chain.c, with the drive swap
 * the only thing ever left resident; MEM (memtest86+ through linux.c, as
 * jump boots it). No ISO scan, virtual CD, Windows media or BSD code is in
 * this stage 3. Stages 1 and 2 are the stick's, unchanged.
 *
 * What the rows are called, what a STATION.INI section does to them and the
 * order they are shown in are falcon-core's media/strows.c, the UEFI
 * station's list too; this file finds the rows and boots them. The
 * sentences are the UEFI station's (apps/station/efi_main.c), listed in
 * docs/notes/station-rework.md section 11; a change to one is a change to
 * the other (CLAUDE.md, "One screen, two loaders").
 */

