/* The disks an install's partitions are looked for on: the boot drive,
 * then every fixed disk the BIOS counts (disk/install.h). A partition is
 * taken by its record's install ID, never by the disk it is on, so the rig
 * disk a corpus case adds and a machine's internal disk are asked the same
 * question and only this install's partitions answer. */
#define DISKS_MAX 8u

/* Caller-allocated, as everywhere in falcon-core, and static rather than on
 * the stack because stage 3's stack is 64 KB (biosdefs.h, STAGE3_STACK).
 * One array per disk: g_p2_part and g_p3_part point into these for the life
 * of the loader. */
#define PARTS_MAX 16u
static part_entry g_parts[DISKS_MAX][PARTS_MAX];
static bios_disk  g_disks[DISKS_MAX];

/* The boot partition's record: the install everything else must belong to
 * (DESIGN Section 3.1). */
static ident_rec     g_install;
static int           g_have_install;
static install_state g_install_state;

/* The ISO partition, once found, and the offset shim that turns a
 * disk-relative callback into a partition-relative one. Same shape as
 * medium.c's, and for the same reason: everything above wants to think it is
 * reading a volume from zero. */
typedef struct {
    bios_disk *disk;
    uint64_t   base;
} part_src;

static part_src g_p2_src;
static fs_vol   g_p2;
static int      g_p2_mounted;

/* p2's own partition entry and the block size it was read with: between
 * them they are what names the partition to falcon-hook, which has to find
 * the same one from Linux (DESIGN Section 6.4). */
static const part_entry *g_p2_part;
static uint32_t          g_p2_block;

/* The shelf and the disk it is on, for the personal-OS row (DESIGN Section
 * 5). */
static const part_entry *g_p3_part;
static bios_disk        *g_p3_disk;

/* What the menu draws, from falcon-core's survey (media/survey.c): the same
 * walk, extension rule, sort and folder view the UEFI loader uses. The
 * results are kept rather than re-read, because re-walking to redraw a row
 * would mean a thunk call per sector per keystroke.
 *
 * ISO and IMG only: nothing on a BIOS machine runs a PE, so the .efi rows
 * the UEFI menu offers would be rows that cannot boot. */
#define MENU_MAX 128u
/* The core rows, plus "..", plus the personal-OS row. */
#define VIEW_MAX (MENU_MAX + 2u)

static survey_entry g_entries[MENU_MAX];
static survey_list  g_survey;
static survey_row   g_view[VIEW_MAX];

/* What the background probe found for each survey entry
 * (media/biosboot.h), kept for the run: choosing an entry, or the next-boot
 * marker naming it, reads the same answer rather than a second one. */
typedef struct {
    uint8_t done;
    uint8_t efi_only;   /* no route here reaches it: {EFI ONLY} */
    uint8_t needs64;    /* every way in needs long mode */
} entry_probe;

static entry_probe g_probe[MENU_MAX];

/* Whether this processor has long mode, asked once: {64-BIT ONLY} is shown
 * only where it has not. */
static int g_cpu64;

/* Where the menu is. Empty at p2's root. */
static uint16_t g_cur[SURVEY_PATH_MAX];
static size_t   g_cur_len;

/* Whether the menu has a personal-OS row, which it does when the shelf
 * opened, as LUKS2 or as a plaintext filesystem. One row, first on the root
 * screen, as under UEFI. */
static int g_pos_row;

/* The next-boot marker (DESIGN Section 6.3.1): taken off the boot disk, and
 * cleared, before anything else is read; acted on once the survey exists. */
static marker_state g_next_state;
static char         g_next[NEXTBOOT_MAX];

static int part_read(void *ctx, uint64_t off, uint64_t len, void *buf)
{
    const part_src *p = ctx;

    if (off > ~(uint64_t)0 - p->base)
        return -1;
    /* bios_disk_bytes, not bios_disk_read: the drivers above read parts of
     * a sector on a 4Kn disk (DESIGN Section 3.4). base is whole sectors,
     * so the layer sees the drivers' alignment unchanged. */
    return bios_disk_bytes(p->disk, p->base + off, len, buf);
}

static void put_name(const uint16_t *name)
{
    size_t i;

    for (i = 0; name[i] != 0; i++)
        bios_putc(bios_ascii(name[i], '?'));
}

/* ---- the menu (DESIGN Section 6 stage 1) ----
 *
 * The rows are the UEFI loader's view_build, in its order: the personal-OS
 * row first on the root screen, ".." first in a folder, then the folders and
 * files the survey found. What a folder holds comes from falcon-core
 * (media/survey.c), so the two platforms cannot disagree about what is on a
 * stick; how the menu is drawn comes from falcon-core too (tui/tui.c), so
 * they cannot disagree about how it looks. The UEFI menu's firmware-setup
 * row has no counterpart: nothing asks a BIOS to open its setup screen. */

typedef enum {
    ROW_PERSONAL,   /* the personal-OS row; root screen only */
    ROW_UP,         /* leave the current folder */
    ROW_DIR,        /* descend into the folder this row names */
    ROW_IMAGE       /* boot survey entry g_row_index */
} row_kind;

/* The rows the list draws, their tag columns filled from the background
 * probe (probe_fill). */
static tui_row         g_rows[VIEW_MAX];
static row_kind        g_kind[VIEW_MAX];
static size_t          g_row_index[VIEW_MAX];

/* The ".." row doubles as the only place the current folder is named, as
 * on the UEFI menu. */
static uint16_t g_up_label[SURVEY_PATH_MAX + 16u];

static void up_label(void)
{
    static const uint16_t head[] = u"..  (now in /";
    size_t n = 0;
    size_t i;

    for (i = 0; head[i] != 0 && n + 2u < sizeof g_up_label / 2u; i++)
        g_up_label[n++] = head[i];
    for (i = 0; i < g_cur_len && n + 2u < sizeof g_up_label / 2u; i++)
        g_up_label[n++] = g_cur[i];
    g_up_label[n++] = u')';
    g_up_label[n] = 0;
}

/* Looks inside survey entry idx once, silently (iso/scan.h). A .img is a
 * disk, not a CD: neither question is asked of it. */
static const entry_probe *probe_entry(size_t idx)
{
    entry_probe *p = &g_probe[idx];
    const survey_entry *e = &g_survey.entries[idx];
    biosboot_result r;

    if (p->done)
        return p;
    /* done is set last, so a probe abandoned part way (probe_stop) leaves
     * the entry to be looked inside again. */
    if (e->media == SURVEY_MEDIA_CD) {
        scan_probe(&g_p2, &e->ent, &r);
        p->efi_only = r.boots == BIOSBOOT_NO;
        p->needs64 = r.needs64 == BIOSBOOT_YES;
    }
    p->done = 1;
    return p;
}

/* The row's reason, or NULL (DESIGN Section 7.8): {EFI ONLY} for a medium
 * nothing here can start, {64-BIT ONLY} for one only a processor this one is
 * not can run. */
static const uint16_t *entry_why(const entry_probe *p)
{
    if (p->efi_only)
        return u"{EFI ONLY}";
    if (p->needs64 && !g_cpu64)
        return u"{64-BIT ONLY}";
    return (const uint16_t *)0;
}

/* The row's tags from its entry's answer. */
static void row_tags(size_t row)
{
    tui_row *t = &g_rows[row];

    t->why = entry_why(&g_probe[g_row_index[row]]);
    t->caution = t->why != (const uint16_t *)0;
}

/* ---- the background probe (DESIGN Section 7.8) ----
 *
 * As the UEFI loader's (apps/stick/efi_main.c): every entry is looked
 * inside on a task of its own (task/task.h) for as long as a menu is up, in
 * core's order (survey_next_probe), yielding to the menu from the disk
 * layer's hook on each new tick or every PROBE_YIELD_READS reads, since
 * a machine can reach the menu with IRQ0 never delivered. Anything that
 * leaves the menu to act stops it first (probe_stop). */
#define PROBE_STACK_BYTES 0x20000u   /* 128 KiB */
#define PROBE_YIELD_READS 32u

static task     g_probe_task;
static uint8_t  g_probe_stack[PROBE_STACK_BYTES];
static size_t   g_probe_want = MENU_MAX;
static uint32_t g_probe_tick;
static unsigned g_probe_reads;

static int probe_done(void *ctx, size_t i)
{
    (void)ctx;
    return g_probe[i].done;
}

static size_t probe_next(void)
{
    return survey_next_probe(&g_survey, g_cur, g_cur_len, g_probe_want,
                             probe_done, (void *)0);
}

static void probe_body(void *arg)
{
    size_t i;

    (void)arg;
    while ((i = probe_next()) < g_survey.count)
        (void)probe_entry(i);
}

/* bios_disk_bytes' hook: from inside the probe, back to the menu on a new
 * tick of the BIOS clock, or after enough reads without one. */
static void probe_yield(void)
{
    uint32_t now;

    if (!task_in())
        return;
    now = peek32(0x46Cu);    /* the BIOS data area's tick count */
    if (now != g_probe_tick || ++g_probe_reads >= PROBE_YIELD_READS) {
        g_probe_tick = now;
        g_probe_reads = 0;
        task_yield();
    }
}

static void probe_stop(void)
{
    task_abandon(&g_probe_task);
}

static int probe_step(void *ctx, size_t sel)
{
    (void)ctx;
    g_probe_want = g_kind[sel] == ROW_IMAGE ? g_row_index[sel] : MENU_MAX;
    if (g_probe_task.state == TASK_IDLE) {
        if (probe_next() >= g_survey.count)
            return 0;
        task_start(&g_probe_task, g_probe_stack, sizeof g_probe_stack,
                   probe_body, (void *)0);
    }
    return task_resume(&g_probe_task);
}

static int probe_fill(void *ctx, size_t row)
{
    (void)ctx;
    if (g_kind[row] != ROW_IMAGE)
        return 1;
    if (!g_probe[g_row_index[row]].done)
        return 0;
    row_tags(row);
    return 1;
}

/* Appends s, or v in decimal, at n in a buffer of cap; returns the new
 * length, the buffer terminated. */
static size_t add(char *b, size_t n, size_t cap, const char *s)
{
    while (*s != '\0' && n + 1u < cap)
        b[n++] = *s++;
    b[n] = '\0';
    return n;
}

static size_t dec(char *b, size_t n, size_t cap, size_t v)
{
    char d[20];
    size_t k = 0;

    do {
        d[k++] = (char)('0' + v % 10u);
        v /= 10u;
    } while (v != 0 && k < sizeof d);
    while (k > 0 && n + 1u < cap)
        b[n++] = d[--k];
    b[n] = '\0';
    return n;
}

/* The bottom border: the highlighted image's size. */
static void view_detail(void *ctx, size_t row, uint16_t *buf, size_t cap)
{
    (void)ctx;
    buf[0] = 0;
    if (g_kind[row] == ROW_IMAGE)
        tui_size(buf, cap, g_survey.entries[g_row_index[row]].ent.size);
}

/* The line under the panel: the library's count, and what the probe has
 * still to look inside. */
static void view_note(void *ctx, uint16_t *buf, size_t cap)
{
    size_t left = 0;
    size_t n = 0;
    size_t i;
    char line[64];

    (void)ctx;
    for (i = 0; i < g_survey.count; i++) {
        if (!g_probe[i].done)
            left++;
    }
    n = dec(line, n, sizeof line, g_survey.count);
    n = add(line, n, sizeof line, g_survey.count == 1 ? " image" : " images");
    if (left != 0) {
        n = add(line, n, sizeof line, ", ");
        n = dec(line, n, sizeof line, left);
        n = add(line, n, sizeof line, " still being read");
    }
    for (i = 0; i < n && i + 1u < cap; i++)
        buf[i] = (uint16_t)(unsigned char)line[i];
    buf[i] = 0;
}

static size_t view_build(void)
{
    size_t n = 0;
    size_t j;
    size_t i;

    /* Only an image row has anything to look inside; every other row is
     * done as built, so it never shows the pending placeholder. */
    memset(g_rows, 0, sizeof g_rows);
    for (i = 0; i < VIEW_MAX; i++)
        g_rows[i].probed = 1;

    if (g_cur_len == 0u) {
        if (g_pos_row) {
            g_rows[n].label = pos_entry_label();
            g_kind[n] = ROW_PERSONAL;
            n++;
        }
    } else {
        up_label();
        g_rows[n].label = g_up_label;
        g_kind[n] = ROW_UP;
        n++;
    }
    j = survey_view(&g_survey, g_cur, g_cur_len, g_view, VIEW_MAX - n);
    for (i = 0; i < j && n < VIEW_MAX; i++) {
        g_rows[n].label = g_view[i].label;
        g_kind[n] = (g_view[i].kind == SURVEY_ROW_DIR) ? ROW_DIR : ROW_IMAGE;
        g_row_index[n] = (size_t)g_view[i].index;
        /* An image already looked inside, on an earlier screen, has its
         * answer kept: its tags are filled here and the menu skips it. */
        if (g_kind[n] == ROW_IMAGE) {
            if (g_probe[g_row_index[n]].done)
                row_tags(n);
            else
                g_rows[n].probed = 0;
        }
        n++;
    }
    return n;
}

/* ---- boot routes, reported the way the UEFI loader reports them ---- */

/* A route that came back: a red dialog titled "<what> failed", the label,
 * then any line the route adds, "<what> failed while <stage>", the advice
 * and any hint. */
static void failed(const uint16_t *label, const char *what,
                   const boot_result *r, const char *head, const char *line,
                   const char *hint)
{
    uint16_t title[48];
    size_t n = 0;
    size_t i;

    for (i = 0; what[i] != '\0' && n + 8u < sizeof title / sizeof title[0];
         i++)
        title[n++] = (uint16_t)(unsigned char)what[i];
    for (i = 0; u" failed"[i] != 0; i++)
        title[n++] = u" failed"[i];
    title[n] = 0;
    tui_report(TUI_FAIL, title, label);
    if (line != (const char *)0 && line[0] != '\0') {
        tui_out_ascii(head);
        tui_out_ascii(line);
        tui_out(u"\n");
    }
    tui_report_failed_a(what, r->stage);
    if (r->advice != (const char *)0) {
        tui_out(u"\n");
        tui_style(TUI_DIM);
        tui_out_ascii(r->advice);
        tui_out(u"\n");
        tui_style(TUI_PLAIN);
    }
    if (hint != (const char *)0) {
        tui_out(u"\n");
        tui_style(TUI_DIM);
        tui_out_ascii(hint);
        tui_out(u"\n");
        tui_style(TUI_PLAIN);
    }
    tui_report_end((const uint16_t *)0);
}

/* The dialog a tagged row shows instead of a route: nothing is loaded, so
 * there is no route code, only what the medium is and what to do. */
static void refuse(const survey_entry *e, const char *title, const char *why,
                   const char *what)
{
    uint16_t t[24];
    size_t i;

    for (i = 0; title[i] != '\0' && i + 1u < sizeof t / sizeof t[0]; i++)
        t[i] = (uint16_t)(unsigned char)title[i];
    t[i] = 0;
    tui_report(TUI_INFO, t, e->label);
    tui_out_ascii(why);
    tui_out(u"\n\n");
    tui_style(TUI_DIM);
    tui_out_ascii(what);
    tui_out(u"\n");
    tui_style(TUI_PLAIN);
    tui_report_end((const uint16_t *)0);
}

/* Windows install media with boot.wim patched in memory (DESIGN Section
 * 6.4). 0 when the medium is not one the patch applies to, with the caller
 * left to boot it as it is. */
static int boot_windows(const survey_entry *e)
{
    char rel[MANIFEST_PATH_MAX];
    boot_result r;
    int unpatchable = 1;

    /* The whole path from p2's root, not the file's name: winjump looks for
     * exactly this under every drive letter, and an ISO in a folder is not
     * at the root of any of them. Converted by the rule the UEFI loader and
     * the manifest use, so a path it cannot carry is booted unpatched
     * rather than turned into one winjump will never find. */
    if (manifest_path_from_ucs2(e->label, rel, sizeof rel) != MANIFEST_OK)
        return 0;
    boot_result_init(&r);
    tui_boot_page(e->label, u"WIN");
    (void)win_boot(g_p2_src.disk, &g_p2, g_p2_part, &e->ent, rel, &r,
                   &unpatchable);
    if (unpatchable)
        return 0;

    failed(e->label, "boot", &r, (const char *)0, (const char *)0,
           (const char *)0);
    return 1;
}

/* Windows 2000/XP text-mode setup media: the virtual-CD driver injected into
 * setup (DESIGN Section 6.3). 0 when the medium is not
 * 2000/XP media, so the caller boots it as it is. */
static int boot_windows_xp(const survey_entry *e)
{
    boot_result r;
    int not_xp = 1;

    boot_result_init(&r);
    tui_boot_page(e->label, u"WXP");
    (void)win_xp_boot(g_p2_src.disk, &g_p2, g_p2_part, &e->ent, &r, &not_xp);
    if (not_xp)
        return 0;

    failed(e->label, "Windows setup", &r, (const char *)0, (const char *)0,
           (const char *)0);
    return 1;
}

/* A BSD medium served as its own memory disk (DESIGN Section 6.4). 0 when
 * the medium is not one this route applies to. */
static int boot_bsd(const survey_entry *e)
{
    boot_result r;
    int not_bsd = 1;

    boot_result_init(&r);
    tui_boot_page(e->label, u"BSD");
    (void)bsd_boot(g_p2_src.disk, &g_p2, g_p2_part, &e->ent, &r, &not_bsd);
    if (not_bsd)
        return 0;

    failed(e->label, "the memory-disk boot", &r, (const char *)0,
           (const char *)0, (const char *)0);
    return 1;
}

static void boot_target(const survey_entry *e, const family_desc *fam);

/* The ISO's kernel, directly, with falcon-hook (DESIGN Section 6.4). An ISO
 * this route cannot take (no boot entry it can read, a kernel that is not
 * one it can start) goes on to its own loader, as on the UEFI loader
 * (docs/Manual.md, Section 2.3): that is what Enter on DOS, BSD or anything
 * else that is not Linux means. A failure after the route committed is
 * reported here. */
static void boot_direct(const survey_entry *e, const family_desc *fam)
{
    boot_result r;

    boot_result_init(&r);
    tui_boot_page(e->label, u"DIR");
    (void)scan_direct(&g_p2, g_p2_part, &e->ent, g_p2_block, &r);
    if (r.fallthrough) {
        boot_target(e, fam);
        return;
    }

    failed(e->label, "direct boot", &r, "entry: ", r.title,
           "press c on the entry to boot the ISO's own loader instead.");
}

/* The medium's own bootloader, off the resident virtual CD. */
static void boot_target(const survey_entry *e, const family_desc *fam)
{
    boot_result r;

    boot_result_init(&r);
    tui_boot_page(e->label, u"CHN");
    (void)scan_chain(g_p2_src.disk, &g_p2, g_p2_part, &e->ent, &r);

    failed(e->label, "boot", &r, "family: ",
           fam != (const family_desc *)0 ? fam->name : (const char *)0,
           (const char *)0);
}

/* What the UEFI loader's boot_plain decides, in its order: Windows media is
 * patched, BSD media is served as a memory disk, anything else boots its
 * kernel directly, and c boots the medium's own loader. The one difference
 * is BSD media this route does not apply to, which goes on to the direct
 * boot here rather than to the chainload (docs/Manual.md, Section 2.3). */
static void boot_plain(size_t idx, int which)
{
    const survey_entry *e = &g_survey.entries[idx];
    const entry_probe *p;
    const family_desc *fam;
    int chain = (which == 'c');
    int id;

    /* Looking inside the medium reads it: say so rather than leave the
     * menu frozen until the route's page. */
    tui_page(e->label, u"");
    tui_step(tui_busy_image);
    p = probe_entry(idx);

    /* Every key, c included: the chainload wants a BIOS boot image this
     * medium does not have, and direct a kernel it does not carry, or one
     * this processor cannot run (DESIGN Section 7.8). */
    if (p->efi_only) {
        refuse(e, "EFI only", "this image boots only on a UEFI machine: it "
                              "has no BIOS boot image, and no kernel "
                              "falcon-bios can start.",
               "Start the machine from this stick in UEFI mode instead.");
        return;
    }
    if (p->needs64 && !g_cpu64) {
        refuse(e, "64-bit only", "this image needs a 64-bit processor, and "
                                 "this one has no 64-bit mode.",
               "Start it on a machine with a 64-bit processor instead.");
        return;
    }
    fam = scan_family(&g_p2, &e->ent);
    id = (fam != (const family_desc *)0) ? (int)fam->id : -1;

    if (!chain && id == (int)FAMILY_WINDOWS) {
        /* boot.wim media (Vista and later) go through win_boot; 2000/XP have
         * no boot.wim and fall to the text-mode-setup injection. */
        if (!boot_windows(e) && !boot_windows_xp(e))
            boot_target(e, fam);
        return;
    }
    if (!chain && id == (int)FAMILY_BSD && boot_bsd(e))
        return;
    if (!chain) {
        boot_direct(e, fam);
        return;
    }
    boot_target(e, fam);
}

/* The personal-OS row (DESIGN Section 5). 0 when the user backed out, which
 * leaves nothing on screen worth a keypress. */
static int boot_personal(void)
{
    boot_result r;

    tui_boot_page(pos_entry_label(), u"POS");
    if (pos_run(g_p3_disk, g_p3_part, &r) == POS_ABORTED)
        return 0;
    tui_route_failed_a(pos_entry_label(), "personal OS boot", r.stage,
                       r.advice);
    return 1;
}

/* Escape at the root, as on the UEFI menu: say so, and give the machine back
 * to its firmware, which on a BIOS is INT 18h, the call a boot sector makes
 * when it has nothing to boot. A BIOS that answers it by returning gets a
 * reset instead. */
static void return_to_firmware(void)
{
    tui_leaving(0);
    if (!g_p2_mounted)
        tui_out(u"note: no readable ISO volume was found.\n");
    if (g_survey.skipped != 0) {
        tui_out(u"note: ");
        tui_out_dec(g_survey.skipped);
        tui_out(u" image(s) not shown (list full or path too long)\n");
    }
    tui_handoff();
    thunk_vector = 0x18;
    thunk_bios();
    bios_reboot();
}

/* Said once, before the menu, when the loader could not learn its install:
 * the menu that follows offers no library and no shelf, and without this it
 * would not say why. The UEFI loader's install_notice. */
static void install_notice(void)
{
    const char *why = install_problem(g_install_state);

    if (why == (const char *)0)
        return;
    tui_notice_a(u"This install", why);
}

/* The next-boot marker, acted on: the UEFI loader's next_boot_run, in its
 * order and with its sentences. The marker was cleared before any of this
 * ran, so every path below, including a boot that starts and comes back,
 * leaves nothing on the disk to repeat. Returns with a key taken, and the
 * menu follows.
 *
 * The value is matched against paths the survey found, never used as one,
 * and the match boots the entry exactly as Enter on its row would: the same
 * boot_plain, not a second policy. */
static void next_boot_run(void)
{
    const char *note = (const char *)0;
    size_t i;

    switch (g_next_state) {
    case MARKER_NONE:
        return;
    case MARKER_BAD:
        note = "the next-boot marker held something that is not a path on "
               "this stick.";
        break;
    case MARKER_STALE:
        note = "the next-boot marker was not set within the last ten "
               "minutes.";
        break;
    case MARKER_NO_CLOCK:
        note = "this machine's clock did not answer, so the next-boot marker "
               "could not be dated.";
        break;
    case MARKER_STUCK:
        note = "the next-boot marker could not be cleared, so nothing was "
               "booted from it.";
        break;
    case MARKER_VALUE:
    default:
        break;
    }

    if (note != (const char *)0) {
        tui_next_note(note, g_next_state != MARKER_STUCK);
        return;
    }

    /* Reserved values first: they can never match a path, and testing them
     * afterwards would report "not on the stick any more" for something that
     * was never a file. */
    if (nextboot_is_reserved(g_next)) {
        if (nextboot_is_personal(g_next) && g_pos_row) {
            if (boot_personal())
                (void)tui_wait();
            return;
        }
        tui_next_note(nextboot_is_personal(g_next)
                          ? "the personal OS the next-boot marker names is "
                            "not on this stick."
                          : "the next-boot marker held a reserved value this "
                            "loader does not know.", 1);
        return;
    }

    for (i = 0; g_p2_mounted && i < g_survey.count; i++) {
        if (nextboot_names(g_survey.entries[i].label, g_next)) {
            boot_plain(i, BIOS_KEY_ENTER);
            (void)tui_wait();
            return;
        }
    }
    tui_next_note("the ISO this boot was supposed to start is not on the "
                  "stick any more.", 1);
}

static void menu_run(void)
{
    /* c and d choose the route for an ISO row; on any other row they act
     * as enter. */
    static const tui_hint hints[] = {
        { u"enter", u"boot" }, { u"c", u"chain" }, { u"d", u"direct" },
        { u"esc", u"back" },
    };
    static uint16_t title[SURVEY_PATH_MAX + 2u];

    for (;;) {
        tui_list l;
        size_t n;
        int which = BIOS_KEY_ENTER;
        int pick;

        n = view_build();
        if (g_cur_len == 0u) {
            ucs2_copy(title, sizeof title / sizeof title[0], u"ISO library");
        } else {
            size_t i;

            title[0] = u'/';
            for (i = 0; i < g_cur_len && i + 2u < sizeof title / 2u; i++)
                title[i + 1u] = g_cur[i];
            title[i + 1u] = 0;
        }
        memset(&l, 0, sizeof l);
        l.title = title;
        l.rows = g_rows;
        l.count = n;
        l.keys = "cd";
        l.hints = hints;
        l.nhints = sizeof hints / sizeof hints[0];
        l.step = probe_step;
        l.fill = probe_fill;
        l.detail = view_detail;
        l.note = view_note;
        pick = tui_list_run(&l, &which);

        if (pick < 0) {
            /* Escape is "back": out of the folder while there is one to
             * leave, out of the loader at the root. */
            if (g_cur_len != 0u) {
                survey_up(g_cur, &g_cur_len);
                continue;
            }
            probe_stop();
            return_to_firmware();
        }

        /* A folder change keeps the probe going; everything else acts, and
         * shares the disk and buffers the probe uses. */
        if (g_kind[pick] != ROW_UP && g_kind[pick] != ROW_DIR)
            probe_stop();
        switch (g_kind[pick]) {
        case ROW_UP:
            survey_up(g_cur, &g_cur_len);
            continue;
        case ROW_DIR:
            (void)survey_enter(g_cur, &g_cur_len, g_rows[pick].label);
            continue;
        case ROW_PERSONAL:
            if (!boot_personal())
                continue;
            break;
        case ROW_IMAGE:
        default:
            boot_plain(g_row_index[pick], which);
            break;
        }
        (void)tui_wait();
    }
}

static uint8_t g_sector[512];

/* Defined below, beside the exFAT state it uses. */
static void scan_iso_partition(bios_disk *d, const part_entry *p);

static void show_first_sector(bios_disk *d, const char *what)
{
    bios_puts("falcon-bios: ");
    bios_puts(what);
    bios_puts(" drive ");
    bios_put_hex64(d->drive);
    bios_puts(", sector size ");
    bios_put_dec(d->sector_size);
    bios_puts("\n");

    if (bios_disk_bytes(d, 0, sizeof g_sector, g_sector) != 0) {
        bios_puts("falcon-bios:   LBA 0 unreadable\n");
        return;
    }
    bios_puts("falcon-bios:   LBA 0 ends ");
    bios_put_hex64((uint64_t)g_sector[510] | ((uint64_t)g_sector[511] << 8));
    bios_puts("\n");
}

static const char *table_error(int rc)
{
    switch (rc) {
    case PART_ERR_IO:          return "the read callback failed";
    case PART_ERR_NO_TABLE:    return "neither an MBR nor a GPT";
    case PART_ERR_CORRUPT:     return "a table that does not check out";
    case PART_ERR_ARG:         return "bad argument";
    case PART_ERR_UNSUPPORTED: return "geometry this parser declines";
    default:                   return "unknown";
    }
}

/* This install's library and shelf, from whichever disk carries them: a
 * partition counts only when its own record names the boot partition's
 * install (DESIGN Section 3.1), and the first of each role is taken. The
 * shelf counts only when it opens (DESIGN Section 12.3, as the UEFI loader
 * has it). Every partition's record is said on serial, the ones that are
 * not this install's too, so a log shows what was passed over and why. */
static void claim_roles(bios_disk *d, const part_table *t)
{
    uint32_t i;

    for (i = 0; i < t->count; i++) {
        const part_entry *p = &t->parts[i];
        ident_rec rec;
        int encrypted = 0;
        int mine;

        bios_puts("falcon-bios:     p");
        bios_put_dec(p->number);
        bios_puts("  LBA ");
        bios_put_dec(p->start_lba);
        bios_puts("..");
        bios_put_dec(p->end_lba);
        if (d->drive == bios_boot_drive && p->start_lba == install_boot_lba()) {
            bios_puts("  [boot]\n");
            continue;
        }
        if (!install_part_record(d, p, &rec, &encrypted)) {
            bios_puts("\n");
            continue;
        }
        mine = g_have_install && ident_same_install(&rec, &g_install);
        bios_puts("  [");
        bios_puts(ident_role_name(rec.role));
        bios_puts(mine ? "]" : ", another install]");
        bios_puts("\n");
        if (!mine)
            continue;
        if (rec.role == IDENT_ROLE_SHELF && g_p3_part == (const part_entry *)0) {
            tui_busy(tui_busy_shelf);
            if (pos_probe(d, p)) {
                g_p3_part = p;
                g_p3_disk = d;
            }
        } else if (rec.role == IDENT_ROLE_LIBRARY && !encrypted &&
                   g_p2_part == (const part_entry *)0) {
            tui_busy(tui_busy_library);
            scan_iso_partition(d, p);
        }
    }
}

/* One disk: its table, and what on it is this install's. */
static void scan_disk(bios_disk *d, part_entry *parts, const char *what)
{
    part_table t;
    int rc;

    show_first_sector(d, what);
    t.parts = parts;
    t.cap = PARTS_MAX;
    rc = part_read_table(&t, bios_disk_read, d, d->sector_size, 0);
    if (rc != PART_OK) {
        bios_puts("falcon-bios:   no partition table: ");
        bios_puts(table_error(rc));
        bios_puts("\n");
        return;
    }
    bios_puts("falcon-bios:   ");
    bios_puts(t.id.kind == PART_KIND_GPT ? "GPT" : "MBR");
    bios_puts(" with ");
    bios_put_dec(t.count);
    bios_puts(" partition(s)");
    if (t.truncated)
        bios_puts(" (more than fitted)");
    bios_puts("\n");
    claim_roles(d, &t);
}

/* Mount the falcon ISO partition and list what the menu would show.
 *
 * Through the registry, which identifies the filesystem rather than being
 * told it: p2 is exFAT today by DESIGN Section 3, and nothing here says so.
 * That was not possible in stage 2, where linking fs.c meant linking every
 * driver it knows and there were 33 KB for all of it. */
static void scan_iso_partition(bios_disk *d, const part_entry *p)
{
    const fs_ops *ops;
    size_t i;

    g_p2_src.disk = d;
    g_p2_src.base = p->start_lba * (uint64_t)d->sector_size;
    g_p2_part = p;
    g_p2_block = d->sector_size;

    ops = fs_identify(part_read, &g_p2_src, FS_HINT_NONE);
    if (ops == (const fs_ops *)0) {
        bios_puts("falcon-bios:   no driver claimed p2\n");
        return;
    }
    if (fs_mount(&g_p2, ops, part_read, &g_p2_src) != FS_OK) {
        bios_puts("falcon-bios:   p2 would not mount\n");
        return;
    }
    g_p2_mounted = 1;
    bios_puts("falcon-bios:   p2 mounted as ");
    bios_puts(fs_vol_name(&g_p2));
    bios_puts(", label ");
    bios_puts(fs_vol_label(&g_p2));
    bios_puts("\n");

    survey_init(&g_survey, g_entries, MENU_MAX,
                SURVEY_ACCEPT_ISO | SURVEY_ACCEPT_IMG);
    if (survey_volume(&g_survey, &g_p2, 0) != 0) {
        bios_puts("falcon-bios:   p2 root unreadable\n");
        return;
    }
    survey_sort(&g_survey);

    /* The whole path, not the name: a stick with its images in Linux/ and
     * Windows/ is the normal case, and a serial log that printed bare names
     * could not tell two fedora.iso apart. */
    for (i = 0; i < g_survey.count; i++) {
        bios_puts("falcon-bios:     ");
        put_name(g_survey.entries[i].label);
        bios_puts("  ");
        bios_put_dec(g_survey.entries[i].ent.size);
        bios_puts(" bytes\n");
    }
    bios_puts("falcon-bios:   ");
    bios_put_dec(g_survey.count);
    bios_puts(" bootable image(s) on p2");
    if (g_survey.skipped != 0u) {
        bios_puts(", ");
        bios_put_dec(g_survey.skipped);
        bios_puts(" past the cap");
    }
    bios_puts("\n");
}

/* The memory map, which the loader needs to place an initrd and the kernel
 * needs because by the time it runs the call that answers is gone. */
static void show_memory(void)
{
    unsigned n = e820_read();
    unsigned i;
    uint64_t usable = 0;

    if (n == 0) {
        bios_puts("falcon-bios: no E820 memory map\n");
        return;
    }
    for (i = 0; i < n; i++) {
        const e820_entry *e = e820_at(i);

        if (e != (const e820_entry *)0 && e->type == E820_USABLE)
            usable += e->len;
    }
    bios_puts("falcon-bios: ");
    bios_put_dec(n);
    bios_puts(" E820 entries, ");
    bios_put_dec(usable / 1048576u);
    bios_puts(" MiB usable\n");
}

void bios_main(uint8_t drive)
{
    uint8_t drives[DISKS_MAX];
    unsigned n;
    unsigned i;

    bios_puts("falcon-bios: C is running in protected mode\n");
    show_memory();
    /* The screen first, so every startup step can say itself on it: a slow
     * disk or a large library shows where the time goes rather than leaving
     * the BIOS's own text up. */
    display_init();
    tui_title(u"falcon-boot " FALCON_VERSION, u"BIOS", TUI_ATTR_STATE);
    tui_busy(tui_busy_disks);

    if (!bios_disk_probe(&g_disks[0], drive))
        bios_puts("falcon-bios: the boot drive did not answer AH=48h\n");
    g_install_state = install_boot_record(&g_disks[0], &g_install);
    g_have_install = g_install_state == INSTALL_OK;
    pos_set_install(g_have_install ? &g_install : (const ident_rec *)0);
    /* First thing after the disk answers, and before anything that can
     * fail: the marker is cleared as it is taken, so from here on nothing on
     * the disk could make this boot happen twice. It is the boot
     * partition's, the one stage 3 was read from: a marker on another disk
     * was not set for this loader. */
    if (g_have_install)
        g_next_state = marker_take(&g_disks[0], install_boot_lba(),
                                   install_marker_sector(), g_next,
                                   sizeof g_next);

    n = install_drives(drive, drives, DISKS_MAX);
    for (i = 0; i < n; i++) {
        if (i != 0 && !bios_disk_probe(&g_disks[i], drives[i]))
            continue;
        scan_disk(&g_disks[i], g_parts[i], i == 0 ? "boot" : "other");
    }

    /* The personal-OS row, if the shelf is there and opens. Asked once,
     * before the menu draws, because the answer does not change. */
    if (g_p3_part != (const part_entry *)0)
        g_pos_row = pos_probe(g_p3_disk, g_p3_part);

    g_cpu64 = linux_cpu_is_64();
    bios_puts("falcon-bios: done\n");
    install_notice();
    next_boot_run();
    bios_disk_set_hook(probe_yield);
    menu_run();
    for (;;)
        __asm__ __volatile__("hlt");
}
