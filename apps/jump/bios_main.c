/* falcon jump (docs/DESIGN.md Section 13): stage 3's entry point in
 * falcon-bios-jump-stage3.bin, the core of the boot floppy.
 *
 * It boots the machine's own disks (route MBR), memtest86+ off the floppy
 * (route MEM) and the disc in an IDE CD drive (route CDR), with an optional
 * default and countdown from JUMP.INI. MBR and MEM load nothing; MEM leaves
 * nothing resident, and MBR only the keyboard block when a USB route left
 * keyboards up (Section 13.6); CDR reads ATA.MOD off the floppy and leaves it behind
 * the reverse thunk, under the stick's own virtual CD (Section 13.6). USB
 * reads a host controller's module and leaves it behind the thunk, serving
 * a falcon stick as the next BIOS disk; PCC does the same with PCC.MOD and
 * a CompactFlash card. Those three routes are falcon-bios's jump/routes.c,
 * which station-legacy links too; this file is jump's menu and pages.
 *
 * Stages 1 and 2: the floppy's own boot sector (start/boot_fd.S) and the
 * stick's stage 2, both reading by CHS from the volume's reserved sectors.
 * The screens and sentences follow the station's bios_main.c, where the
 * routes are the same.
 */

#include <start/bios.h>

#include <mbr/mbr.h>
#include <console/display.h>
#include <linux/linux.h>
#include <mem/e820.h>
#include <jump/jumpini.h>
#include <jump/routes.h>

#include <fs/fs.h>
#include <tui/tui.h>
#include <lib/string.h>

/* Generated by make into build/: this build's version, with the jump-
 * variant, so a photo of the screen says which loader it is. */
#include <version.h>

/* The BDA's count of fixed disks, which is how many drive numbers from 0x80
 * up the BIOS answers for. */
#define BDA_NDISKS 0x475u

#define DISKS_MAX 8u

/* One row per disk, the CD, USB, the CF card, and memtest86+. */
#define LIST_MAX (DISKS_MAX + 4u)

/* What a row of the list is. */
#define ROW_MEMTEST (-1)
#define ROW_CD      (-2)
#define ROW_USB     (-3)
#define ROW_CF      (-4)

/* JUMP.INI is a few lines; anything longer is not one. */
#define INI_MAX 4096u

typedef struct {
    bios_disk disk;
    uint16_t  label[32];
} disk_row;

static disk_row g_disks[DISKS_MAX];
static unsigned g_ndisks;

/* The floppy jump booted from, and its volume. */
static bios_disk g_fd;
static fs_vol    g_vol;
static int       g_have_vol;
static fs_dirent g_memtest;
static int       g_have_memtest;


static jump_cfg g_cfg;
static char     g_ini[INI_MAX];


/* "Disk 0x80", in UCS-2 for the menu. */
static void disk_label(disk_row *row)
{
    static const uint16_t head[] = u"Disk 0x";
    static const char hex[] = "0123456789abcdef";
    size_t n = 0;
    size_t i;

    for (i = 0; head[i] != 0; i++)
        row->label[n++] = head[i];
    row->label[n++] = (uint16_t)hex[(row->disk.drive >> 4) & 0xFu];
    row->label[n++] = (uint16_t)hex[row->disk.drive & 0xFu];
    row->label[n] = 0;
}

/* Every disk the BDA counts whose LBA 0 carries boot code. */
static void scan_disks(void)
{
    unsigned count = peek8(BDA_NDISKS);
    unsigned i;

    for (i = 0; i < count && g_ndisks < DISKS_MAX; i++) {
        disk_row *row = &g_disks[g_ndisks];

        if (!bios_disk_probe(&row->disk, (uint8_t)(0x80u + i)))
            continue;
        if (!mbr_bootable(&row->disk))
            continue;
        disk_label(row);
        bios_puts("falcon-bios: drive ");
        bios_put_hex64(row->disk.drive);
        bios_puts(", boot code in LBA 0\n");
        g_ndisks++;
    }
}

/* The floppy's read callback: bios_disk_read, except that sector 0 comes
 * from STAGE1_LOAD, where the BIOS put it. Reading it again costs a seek
 * back to cylinder 0 and a revolution, about a third of a second, for 512
 * bytes already in memory (DESIGN Section 13.3). What is at STAGE1_LOAD is
 * the sector as the BIOS read it, with boot_fd.S's variables since
 * written into its code; the BPB and the signature, which are all the FAT
 * driver reads of it, are as on the disk. Nothing writes STAGE1_LOAD before
 * a route starts, and every route reads the floppy before it does. */
static int fd_read(void *ctx, uint64_t off, uint64_t len, void *buf)
{
    uint8_t *out = buf;

    if (off == 0 && len >= 512u && peek8(STAGE1_LOAD + 510u) == 0x55u &&
        peek8(STAGE1_LOAD + 511u) == 0xAAu) {
        memcpy(out, (const void *)(uintptr_t)STAGE1_LOAD, 512u);
        off += 512u;
        len -= 512u;
        out += 512u;
        if (len == 0)
            return 0;
    }
    return bios_disk_read(ctx, off, len, out);
}

/* The floppy's volume, JUMP.INI and MEMTEST.BIN. A floppy that will not
 * mount leaves both routes that need it off the menu and says so on serial;
 * the disks still boot. */
static void read_floppy(uint8_t drive)
{
    const fs_ops *ops;
    fs_dir scratch;
    fs_dirent ini;
    fs_file f;

    g_cfg.def = JUMP_DEF_NONE;
    g_cfg.timeout = 0;
    g_cfg.err_line = 0;

    if (!bios_disk_probe(&g_fd, drive)) {
        bios_puts("falcon-bios: the boot floppy did not answer\n");
        return;
    }
    ops = fs_identify(fd_read, &g_fd, FS_HINT_NONE);
    if (ops == (const fs_ops *)0 ||
        fs_mount(&g_vol, ops, fd_read, &g_fd) != FS_OK) {
        bios_puts("falcon-bios: the boot floppy is not a FAT volume\n");
        return;
    }
    g_have_vol = 1;

    g_have_memtest =
        fs_lookup(&g_vol, "/MEMTEST.BIN", &scratch, &g_memtest) == FS_OK &&
        !g_memtest.is_dir && g_memtest.size > 0;

    if (fs_lookup(&g_vol, "/JUMP.INI", &scratch, &ini) != FS_OK || ini.is_dir)
        return;
    if (ini.size > INI_MAX ||
        fs_file_open(&g_vol, &f, &ini) != FS_OK ||
        fs_file_read(&f, 0, ini.size, g_ini) != FS_OK) {
        static const char why[] = "the file could not be read";
        size_t k;

        _Static_assert(sizeof why <= sizeof g_cfg.why,
                       "the sentence fits jump_cfg's buffer");
        for (k = 0; k < sizeof why; k++)
            g_cfg.why[k] = why[k];
        g_cfg.err_line = 1;
        bios_puts("falcon-bios: JUMP.INI could not be read\n");
        return;
    }
    (void)jump_ini_parse(g_ini, (size_t)ini.size, &g_cfg);
}

/* A disk's own boot code reads the keyboard through the BIOS, so USB
 * keyboards a route left up go behind INT 16h for it (DESIGN Section
 * 13.6); with none up, nothing is resident. */
static void boot_disk(disk_row *row)
{
    boot_result r;
    int kb;

    boot_result_init(&r);
    tui_boot_page(row->label, u"MBR");
    kb = jroute_kbd_install();
    (void)mbr_boot(&row->disk, &r);
    if (kb == 0)
        jroute_kbd_remove();

    tui_route_failed_a(row->label, "boot", r.stage, r.advice);
}

static void boot_memtest(void)
{
    boot_result r;
    fs_file f;
    linux_object k;

    boot_result_init(&r);
    tui_boot_page(u"memtest86+", u"MEM");

    jroute_kbd_release();
    boot_stage(&r, "opening MEMTEST.BIN");
    if (fs_file_open(&g_vol, &f, &g_memtest) == FS_OK) {
        k.read = fs_file_read_cb;
        k.ctx = &f;
        k.size = g_memtest.size;
        boot_stage(&r, "starting memtest86+");
        (void)linux_boot(&k, (const linux_object *)0, 0, "", tui_handoff);
        boot_result_advise(&r, linux_why(), (const char *)0);
    }

    tui_route_failed_a(u"memtest86+", "boot", r.stage, r.advice);
}

/* CD, USB and CF: jump/routes.c between this app's two pages. */
static void boot_route(jroute k, const uint16_t *name)
{
    boot_result r;

    boot_result_init(&r);
    tui_code_ascii(jroute_code(k));
    tui_boot_page(name, (const uint16_t *)0);
    jroute_boot(k, &r);

    tui_route_failed_a(name, "boot", r.stage, r.advice);
}

/* Escape on the list: INT 18h, and a reset if the BIOS returns. */
static void return_to_firmware(void)
{
    tui_leaving(0);
    tui_handoff();
    jroute_kbd_release();
    thunk_vector = 0x18;
    thunk_bios();
    bios_reboot();
}

/* A JUMP.INI that could not be taken, said once before the menu, which then
 * waits with no default. */
static void report_ini(void)
{
    tui_ini_line("JUMP.INI", (unsigned)g_cfg.err_line, g_cfg.why);
}

static void list_run(void)
{
    static const tui_hint hints[] = {
        { u"enter", u"boot" }, { u"up/down", u"choose" },
        { u"esc", u"firmware" },
    };
    static const uint16_t *labels[LIST_MAX];
    static tui_row rows[LIST_MAX];
    static int kind[LIST_MAX];      /* ROW_*, else a g_disks slot */
    unsigned seconds = g_cfg.timeout;

    for (;;) {
        size_t n = 0;
        size_t def = 0;
        int have_def = 0;
        unsigned i;
        int pick;
        tui_list l;

        for (i = 0; i < g_ndisks; i++) {
            if (g_cfg.def == JUMP_DEF_HDD && !have_def) {
                def = n;
                have_def = 1;
            }
            labels[n] = g_disks[i].label;
            kind[n] = (int)i;
            n++;
        }
        if (jroute_offered(JROUTE_CD)) {
            if (g_cfg.def == JUMP_DEF_CD) {
                def = n;
                have_def = 1;
            }
            labels[n] = u"CD drive";
            kind[n] = ROW_CD;
            n++;
        }
        if (jroute_offered(JROUTE_CF)) {
            if (g_cfg.def == JUMP_DEF_CF) {
                def = n;
                have_def = 1;
            }
            labels[n] = u"CF card (PC Card)";
            kind[n] = ROW_CF;
            n++;
        }
        if (jroute_offered(JROUTE_USB)) {
            if (g_cfg.def == JUMP_DEF_USB) {
                def = n;
                have_def = 1;
            }
            labels[n] = u"USB stick";
            kind[n] = ROW_USB;
            n++;
        }
        if (g_have_memtest) {
            if (g_cfg.def == JUMP_DEF_MEMTEST) {
                def = n;
                have_def = 1;
            }
            labels[n] = u"Memory test (memtest86+)";
            kind[n] = ROW_MEMTEST;
            n++;
        }

        /* A default whose row is not there (no disk with boot code, no
         * MEMTEST.BIN, or a route this build does not have yet) is no
         * default: the menu waits rather than booting something else. */
        memset(rows, 0, sizeof rows);
        for (i = 0; i < n; i++) {
            rows[i].label = labels[i];
            rows[i].probed = 1;
        }
        memset(&l, 0, sizeof l);
        l.title = u"Boot from";
        l.rows = rows;
        l.count = n;
        l.sel = def;
        l.seconds = have_def ? seconds : 0;
        l.hints = hints;
        l.nhints = 3;
        l.empty = u"(no disk with boot code, and no MEMTEST.BIN)";
        pick = tui_list_run(&l, (int *)0);
        /* The countdown is the first menu's only; coming back from a failed
         * boot, the menu waits. */
        seconds = 0;
        if (pick < 0)
            return_to_firmware();

        if (kind[pick] == ROW_MEMTEST)
            boot_memtest();
        else if (kind[pick] == ROW_CD)
            boot_route(JROUTE_CD, u"CD");
        else if (kind[pick] == ROW_USB)
            boot_route(JROUTE_USB, u"USB stick");
        else if (kind[pick] == ROW_CF)
            boot_route(JROUTE_CF, u"CF card");
        else
            boot_disk(&g_disks[kind[pick]]);
        (void)tui_wait();
    }
}

void bios_main(uint8_t drive)
{
    unsigned n;

    bios_puts("falcon-bios: jump, protected mode\n");
    /* memtest86+ is placed by the map, and by the time it runs the call
     * that answers is gone. */
    n = e820_read();
    bios_puts("falcon-bios: ");
    bios_put_dec(n);
    bios_puts(" E820 entries\n");

    /* The screen first, so every startup step can say itself on it: a
     * floppy takes seconds to read, and the BIOS's own text would otherwise
     * stay up the whole time. */
    display_init();
    tui_title(u"falcon-boot " FALCON_VERSION_JUMP, u"BIOS", TUI_ATTR_STATE);
    tui_busy(tui_busy_floppy);
    read_floppy(drive);
    jroute_init(g_have_vol ? &g_vol : (fs_vol *)0, "floppy");
    tui_busy(tui_busy_disks);
    scan_disks();

    if (g_cfg.err_line != 0)
        report_ini();
    list_run();
    for (;;)
        __asm__ __volatile__("hlt");
}
