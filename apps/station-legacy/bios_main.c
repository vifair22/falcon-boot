/* falcon-bios, station-legacy (docs/DESIGN.md Section 13.10): stage 3's
 * entry point in falcon-bios-station-legacy-stage3.bin.
 *
 * The BIOS station (falcon-bios's station/station.c), plus the rows falcon
 * jump offers a machine whose BIOS cannot boot them: CD drive, USB stick
 * and CF card (PC Card), each when its controller is on the PCI bus and its
 * driver is in the station partition, booted by jump's own routes
 * (jump/routes.c) with the drivers read off the station partition rather
 * than a floppy. And DevLink recovery, or whatever else the station
 * partition's /uki holds: a plaintext shelf of its own, no prompt, a row
 * per image.
 *
 * The rows are named `cd`, `usb` and `cf`, so STATION.INI's default and
 * next boot can name them as they name any found row.
 */

#include <start/bios.h>

#include <station/station.h>
#include <jump/routes.h>
#include <console/screen.h>

#include <media/strows.h>

/* Generated by make into build/: this build's version, with the
 * station-legacy- variant, so a photo of the screen says which loader it
 * is. */
#include <version.h>

static void add_route(strows *r, jroute k, const char *name,
                      const char *label)
{
    strow *w;
    size_t i;

    if (!jroute_offered(k))
        return;
    w = strows_add(r, STROW_ROUTE);
    if (w == (strow *)0)
        return;
    w->ref = (size_t)k;
    for (i = 0; name[i] != '\0' && i + 1u < sizeof w->name; i++)
        w->name[i] = name[i];
    w->name[i] = '\0';
    for (i = 0; label[i] != '\0' && i + 1u < STROWS_LABEL_MAX; i++)
        w->label[i] = (uint16_t)(uint8_t)label[i];
    w->label[i] = 0;
}

/* After the station's own rows: jump's, in jump's order, then the station
 * partition's /uki. */
static void legacy_rows(strows *r, fs_vol *vol)
{
    jroute_init(vol, "disk");
    add_route(r, JROUTE_CD, "cd", STROWS_LABEL_CD);
    add_route(r, JROUTE_CF, "cf", STROWS_LABEL_CF);
    add_route(r, JROUTE_USB, "usb", STROWS_LABEL_USB);
    (void)station_add_own_shelf();
}

static int legacy_boot(const strow *w)
{
    jroute k = (jroute)w->ref;
    boot_result r;

    boot_result_init(&r);
    screen_mode(jroute_code(k));
    screen_page();
    screen_out("booting: ");
    screen_out16(w->label);
    screen_out("\n\n");
    jroute_boot(k, &r);
    station_failed(w->label, jroute_code(k), &r);
    return 1;
}

static const station_app k_app = {
    "station-legacy", u"falcon-boot " FALCON_VERSION_STATION_LEGACY,
    legacy_rows, legacy_boot
};

void bios_main(uint8_t drive)
{
    station_main(drive, &k_app);
}
