static uint8_t xtime(uint8_t a)
{
    return (uint8_t)((((unsigned)a << 1) & 0xffu) ^ ((((unsigned)a >> 7) & 1u) * 0x1bu));
}

static uint32_t sub_word(uint32_t w)
{
    return ((uint32_t)sbox[(w >> 24) & 0xffu] << 24) |
           ((uint32_t)sbox[(w >> 16) & 0xffu] << 16) |
           ((uint32_t)sbox[(w >> 8) & 0xffu] << 8) |
           (uint32_t)sbox[w & 0xffu];
}

static uint32_t rot_word(uint32_t w)
{
    return (w << 8) | (w >> 24);
}

int aes_setkey(aes_key *k, const uint8_t *key, size_t key_len)
{
    uint32_t nk;
    uint32_t total;
    uint32_t i;
    uint8_t rcon = 1;

    if (k == NULL || key == NULL) {
        return CRYPTO_ERR_BAD_ARG;
    }
    if (key_len == 32u) {
        nk = 8u;
        k->nr = 14u;
    } else if (key_len == 16u) {
        nk = 4u;
        k->nr = 10u;
    } else {
        return CRYPTO_ERR_UNSUPPORTED;
    }

    for (i = 0; i < nk; i++) {
        k->rk[i] = ((uint32_t)key[4u * i] << 24) |
                   ((uint32_t)key[4u * i + 1u] << 16) |
                   ((uint32_t)key[4u * i + 2u] << 8) |
                   (uint32_t)key[4u * i + 3u];
    }

    total = 4u * (k->nr + 1u);
    for (i = nk; i < total; i++) {
        uint32_t t = k->rk[i - 1u];

        if (i % nk == 0u) {
            t = sub_word(rot_word(t)) ^ ((uint32_t)rcon << 24);
            rcon = xtime(rcon);
        } else if (nk > 6u && i % nk == 4u) {
            t = sub_word(t);
        }
        k->rk[i] = k->rk[i - nk] ^ t;
    }
    /* Unused tail of the fixed-size array: zero it so a schedule struct
     * never carries stale key words from an earlier, longer key. */
    for (i = total; i < 4u * (AES_MAX_ROUNDS + 1u); i++) {
        k->rk[i] = 0;
    }
    return CRYPTO_OK;
}

static void add_round_key(uint8_t *s, const uint32_t *rk)
{
    unsigned int c;

    for (c = 0; c < 4u; c++) {
        uint32_t w = rk[c];

        s[4u * c]      = (uint8_t)(s[4u * c] ^ (w >> 24));
        s[4u * c + 1u] = (uint8_t)(s[4u * c + 1u] ^ (w >> 16));
        s[4u * c + 2u] = (uint8_t)(s[4u * c + 2u] ^ (w >> 8));
        s[4u * c + 3u] = (uint8_t)(s[4u * c + 3u] ^ w);
    }
}

static void shift_rows(uint8_t *s)
{
    uint8_t t;

    /* row 1 left by 1 */
    t = s[1]; s[1] = s[5]; s[5] = s[9]; s[9] = s[13]; s[13] = t;
    /* row 2 left by 2 */
    t = s[2]; s[2] = s[10]; s[10] = t;
    t = s[6]; s[6] = s[14]; s[14] = t;
    /* row 3 left by 3 (== right by 1) */
    t = s[15]; s[15] = s[11]; s[11] = s[7]; s[7] = s[3]; s[3] = t;
}

static void inv_shift_rows(uint8_t *s)
{
    uint8_t t;

    t = s[13]; s[13] = s[9]; s[9] = s[5]; s[5] = s[1]; s[1] = t;
    t = s[2]; s[2] = s[10]; s[10] = t;
    t = s[6]; s[6] = s[14]; s[14] = t;
    t = s[3]; s[3] = s[7]; s[7] = s[11]; s[11] = s[15]; s[15] = t;
}

static void mix_columns(uint8_t *s)
{
    unsigned int c;

    for (c = 0; c < 4u; c++) {
        uint8_t *p = s + 4u * c;
        uint8_t a0 = p[0], a1 = p[1], a2 = p[2], a3 = p[3];
        uint8_t t = (uint8_t)(a0 ^ a1 ^ a2 ^ a3);

        p[0] = (uint8_t)(a0 ^ t ^ xtime((uint8_t)(a0 ^ a1)));
        p[1] = (uint8_t)(a1 ^ t ^ xtime((uint8_t)(a1 ^ a2)));
        p[2] = (uint8_t)(a2 ^ t ^ xtime((uint8_t)(a2 ^ a3)));
        p[3] = (uint8_t)(a3 ^ t ^ xtime((uint8_t)(a3 ^ a0)));
    }
}

/* InvMixColumns as a preconditioning step followed by MixColumns.
 *
 * The inverse matrix factors as the forward matrix times a second one whose
 * effect on a column is exactly the u/v adjustment below, so multiplying by
 * {0e,0b,0d,09} becomes four xtime()s and the forward mix. Written out with
 * gmul() it is 16 peasant multiplies per column and measured about ten times
 * slower, which on the fallback path is the difference between a UKI read
 * that finishes and one that looks hung. The identity is checked over the
 * whole input space by the FIPS 197 decrypt vector and by the XTS vectors,
 * which compare this path byte for byte against the AES-NI one. */
static void inv_mix_columns(uint8_t *s)
{
    unsigned int c;

    for (c = 0; c < 4u; c++) {
        uint8_t *p = s + 4u * c;
        uint8_t u = xtime(xtime((uint8_t)(p[0] ^ p[2])));
        uint8_t v = xtime(xtime((uint8_t)(p[1] ^ p[3])));

        p[0] = (uint8_t)(p[0] ^ u);
        p[1] = (uint8_t)(p[1] ^ v);
        p[2] = (uint8_t)(p[2] ^ u);
        p[3] = (uint8_t)(p[3] ^ v);
    }
    mix_columns(s);
}

void aes_encrypt_block(const aes_key *k, const uint8_t *in, uint8_t *out)
{
    uint8_t s[AES_BLOCK];
    uint32_t r;
    unsigned int i;

    memcpy(s, in, AES_BLOCK);
    add_round_key(s, k->rk);
    for (r = 1u; r < k->nr; r++) {
        for (i = 0; i < AES_BLOCK; i++) {
            s[i] = sbox[s[i]];
        }
        shift_rows(s);
        mix_columns(s);
        add_round_key(s, k->rk + 4u * r);
    }
    for (i = 0; i < AES_BLOCK; i++) {
        s[i] = sbox[s[i]];
    }
    shift_rows(s);
    add_round_key(s, k->rk + 4u * k->nr);
    memcpy(out, s, AES_BLOCK);
    crypto_wipe(s, sizeof s);
}

void aes_decrypt_block(const aes_key *k, const uint8_t *in, uint8_t *out)
{
    uint8_t s[AES_BLOCK];
    uint32_t r;
    unsigned int i;

    memcpy(s, in, AES_BLOCK);
    add_round_key(s, k->rk + 4u * k->nr);
    for (r = k->nr; r > 1u; r--) {
        inv_shift_rows(s);
        for (i = 0; i < AES_BLOCK; i++) {
            s[i] = inv_sbox[s[i]];
        }
        add_round_key(s, k->rk + 4u * (r - 1u));
        inv_mix_columns(s);
    }
    inv_shift_rows(s);
    for (i = 0; i < AES_BLOCK; i++) {
        s[i] = inv_sbox[s[i]];
    }
    add_round_key(s, k->rk);
    memcpy(out, s, AES_BLOCK);
    crypto_wipe(s, sizeof s);
}
