/* falcon-boot: AES-128/256, portable C (FIPS 197). See aes.h.
 *
 * State layout follows FIPS 197 Section 3.4: the 16 input bytes fill the
 * state column by column, so s[i] is row i%4 of column i/4. Round keys are
 * held as the expanded words w[] of Section 5.2, and AddRoundKey applies
 * word w[4r+c] to column c most-significant-byte first.
 *
 * The field arithmetic is GF(2^8) modulo x^8+x^4+x^3+x+1, and xtime() -
 * multiplication by x with the conditional reduction - is the only
 * primitive: both MixColumns and its inverse are expressed in terms of it
 * (see inv_mix_columns for how the inverse factors through the forward
 * one). No multiplication tables, no T-tables. This path exists to be
 * auditable and to work everywhere; xts.c hands the hot case to aesni.c
 * whenever CPUID allows.
 */

